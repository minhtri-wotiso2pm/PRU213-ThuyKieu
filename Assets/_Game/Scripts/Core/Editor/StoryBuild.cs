using System;
using System.IO;
using System.Linq;
using ThuyKieu.Core.Story;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;

namespace ThuyKieu.Core.Editor
{
    /// <summary>
    /// Batch entry points for the story chapters.
    ///   Rebuild:  -executeMethod ThuyKieu.Core.Editor.StoryBuild.RebuildBatch
    ///   Playtest: -executeMethod ThuyKieu.Core.Editor.StoryBuild.PlaytestBatch -playScene &lt;path&gt; -storyAutopilot [-autopilotChain] -autopilotReport &lt;file&gt;
    /// </summary>
    [InitializeOnLoad]
    public static class StoryBuild
    {
        // Generated by Chapter02Setup / Chapter03Setup only; safe to regenerate.
        private static readonly string[] Generated =
        {
            Chapter02Setup.ScenePath, Chapter03Setup.ScenePath, Chapter03Setup.PlaceholderPath,
            StorySceneKit.UIPrefabPath, StoryAnimationSetup.ControllerPath, StoryAnimationSetup.KieuOverridePath, StorySceneKit.MaterialFolder
        };

        private const string PlaytestKey = "ThuyKieu.StoryPlaytest";

        static StoryBuild()
        {
            if (SessionState.GetBool(RegressionKey, false)) EditorApplication.update += WatchRegression;
            if (!SessionState.GetBool(PlaytestKey, false)) return;
            EditorApplication.update += WatchPlaytest;
        }

        [MenuItem("ThuyKieu/Story/Rebuild Chapter 2 and 3 scenes")]
        public static void Rebuild()
        {
            foreach (string path in Generated)
                if (File.Exists(path) || Directory.Exists(path)) AssetDatabase.DeleteAsset(path);
            AssetDatabase.Refresh();
            StoryMeshLods.Apply();
            Chapter02Setup.Create();
            Chapter03Setup.Create();
            EditorSceneManager.OpenScene(Chapter02Setup.ScenePath);
        }

        public static void RebuildBatch()
        {
            try { Rebuild(); EditorApplication.Exit(0); }
            catch (Exception exception) { Debug.LogException(exception); EditorApplication.Exit(1); }
        }

        public const string WindowsBuildPath = "../Builds/Windows/ThuyKieu.exe"; // outside the repository

        [MenuItem("ThuyKieu/Story/Build Windows (Chapters 1–3)")]
        public static void BuildWindows()
        {
            var scenes = EditorBuildSettings.scenes.Where(s => s.enabled).Select(s => s.path).ToArray();
            var report = BuildPipeline.BuildPlayer(new BuildPlayerOptions
            {
                scenes = scenes,
                locationPathName = WindowsBuildPath,
                target = BuildTarget.StandaloneWindows64,
                options = BuildOptions.None
            });
            Debug.Log("[Build] " + report.summary.result + " · " + report.summary.totalErrors + " errors · " +
                      (report.summary.totalSize / (1024 * 1024)) + " MB · " + report.summary.totalTime);
            if (report.summary.result != UnityEditor.Build.Reporting.BuildResult.Succeeded) throw new Exception("Build failed");
        }

        public static void BuildWindowsBatch()
        {
            try { BuildWindows(); EditorApplication.Exit(0); }
            catch (Exception exception) { Debug.LogException(exception); EditorApplication.Exit(1); }
        }

        public static void PlaytestBatch()
        {
            var args = System.Environment.GetCommandLineArgs();
            int index = Array.IndexOf(args, "-playScene");
            string scene = index >= 0 ? args[index + 1] : Chapter02Setup.ScenePath;
            string report = StoryAutopilot.ReportPath;
            if (File.Exists(report)) File.Delete(report);
            EditorSceneManager.OpenScene(scene);
            SessionState.SetBool(PlaytestKey, true);
            SessionState.SetFloat(PlaytestKey + ".start", (float)EditorApplication.timeSinceStartup);
            EditorApplication.update += WatchPlaytest;
            EditorApplication.EnterPlaymode();
        }

        private const string RegressionKey = "ThuyKieu.Chapter1Regression";

        /// <summary>Runs the existing Chapter 1 Play Mode check headless; exit code 0 when it passes.</summary>
        public static void Chapter1RegressionBatch()
        {
            const string report = "Tools/Chapter01/PlayModeReport.json";
            SessionState.SetString(RegressionKey + ".backup", File.Exists(report) ? File.ReadAllText(report) : string.Empty);
            EditorSceneManager.OpenScene(Chapter01Setup.ScenePath);
            SessionState.SetBool(RegressionKey, true);
            SessionState.SetFloat(RegressionKey + ".start", (float)EditorApplication.timeSinceStartup);
            EditorApplication.update += WatchRegression;
            EditorApplication.EnterPlaymode();
        }

        private static void WatchRegression()
        {
            double elapsed = EditorApplication.timeSinceStartup - SessionState.GetFloat(RegressionKey + ".start", 0f);
            if (!Application.isPlaying) { if (elapsed > 600) FinishRegression("TIMEOUT before play mode"); return; }
            if (!SessionState.GetBool(RegressionKey + ".started", false))
            {
                if (Time.timeSinceLevelLoad < 2f) return;
                SessionState.SetBool(RegressionKey + ".started", true);
                Chapter01PlayModeCheck.Start();
                return;
            }
            if (Chapter01PlayModeCheck.Running && elapsed < 600) return;
            FinishRegression(Chapter01PlayModeCheck.Running ? "TIMEOUT" : null);
        }

        private static void FinishRegression(string error)
        {
            EditorApplication.update -= WatchRegression;
            SessionState.SetBool(RegressionKey, false);
            SessionState.SetBool(RegressionKey + ".started", false);
            const string path = "Tools/Chapter01/PlayModeReport.json";
            string json = File.Exists(path) ? File.ReadAllText(path) : "{}";
            File.WriteAllText("Tools/Ink/Chapter01RegressionReport.json", json);
            // Keep the team's committed Chapter 1 report untouched; the fresh run is saved beside the Ink report.
            string backup = SessionState.GetString(RegressionKey + ".backup", string.Empty);
            if (!string.IsNullOrEmpty(backup)) File.WriteAllText(path, backup);
            bool pass = error == null && json.Contains("\"completed\": true") && json.Contains("\"passed\": true");
            Debug.Log("[Chapter1Regression] " + (error ?? (pass ? "PASS" : "FAIL")) + "\n" + json);
            EditorApplication.Exit(pass ? 0 : 1);
        }

        private static void WatchPlaytest()
        {
            string report = StoryAutopilot.ReportPath;
            double elapsed = EditorApplication.timeSinceStartup - SessionState.GetFloat(PlaytestKey + ".start", 0f);
            bool done = File.Exists(report);
            if (!done && elapsed < 900) return;
            EditorApplication.update -= WatchPlaytest;
            SessionState.SetBool(PlaytestKey, false);
            bool pass = done && File.ReadLines(report).FirstOrDefault()?.StartsWith("AUTOPILOT PASS") == true;
            Debug.Log("[Playtest] " + (done ? File.ReadAllText(report) : "TIMEOUT: no report after " + elapsed.ToString("0") + "s"));
            EditorApplication.Exit(pass ? 0 : 1);
        }
    }
}
