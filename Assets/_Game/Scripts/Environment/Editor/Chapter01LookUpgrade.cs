using System;
using ThuyKieu.Core.Editor;
using ThuyKieu.Player;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;

namespace ThuyKieu.Environment.Editor
{
    /// <summary>
    /// Targeted art pass on the hand-built Chapter 1 scene (it is never regenerated): converts its blockout
    /// materials to CC0 world-space textures in place, adds the rainy night sky and gives the orbit camera
    /// the same over-the-shoulder framing as the later chapters. Re-running it is harmless.
    ///   -executeMethod ThuyKieu.Environment.Editor.Chapter01LookUpgrade.ApplyBatch
    /// </summary>
    public static class Chapter01LookUpgrade
    {
        private const string EnvironmentMaterials = "Assets/_Game/Materials/Chapter01Environment";
        private const string SetupMaterials = "Assets/_Game/Materials";

        [MenuItem("ThuyKieu/Chapter 1/Apply look upgrade")]
        public static void Apply()
        {
            if (Application.isPlaying) throw new InvalidOperationException("Stop Play Mode before the look upgrade.");
            var scene = EditorSceneManager.OpenScene(Chapter01Setup.ScenePath);

            // Night rain washes everything darker and wetter, so tints stay low and stone keeps its sheen.
            Convert(EnvironmentMaterials, "DarkWood", "dark_wood", new Color(0.55f, 0.42f, 0.36f), 1.2f, 0.3f);
            Convert(EnvironmentMaterials, "WoodTrim", "planks_brown_10", new Color(0.6f, 0.42f, 0.32f), 1.4f, 0.3f);
            Convert(EnvironmentMaterials, "WetStone", "monastery_stone_floor", new Color(0.42f, 0.46f, 0.5f), 2.4f, 0.55f, 0.25f, 0.6f);
            Convert(EnvironmentMaterials, "RoofTile", "clay_roof_tiles_02", new Color(0.32f, 0.33f, 0.36f), 1.4f, 0.55f);
            Convert(EnvironmentMaterials, "LimePlaster", "plastered_wall_02", new Color(0.72f, 0.66f, 0.55f), 2.6f, 0.12f, 0.8f);
            Convert(SetupMaterials, "Chapter01Wood", "dark_wood", new Color(0.55f, 0.42f, 0.36f), 1.2f, 0.3f);
            Convert(SetupMaterials, "Chapter01Plaster", "plastered_wall_02", new Color(0.72f, 0.66f, 0.55f), 2.6f, 0.12f, 0.8f);
            Convert(SetupMaterials, "Chapter01Courtyard", "monastery_stone_floor", new Color(0.42f, 0.46f, 0.5f), 2.4f, 0.55f, 0.25f, 0.6f);

            var camera = Camera.main;
            StoryArtKit.UseSky(camera, StoryArtKit.Sky("Ch1SkyRainNight", "kloppenheim_07_puresky", 0.22f, new Color(0.42f, 0.48f, 0.58f), 0f, EnvironmentMaterials));

            var orbit = UnityEngine.Object.FindAnyObjectByType<ThirdPersonCameraController>();
            if (orbit != null)
            {
                StorySceneKit.Set(orbit, "_shoulder", 0.35f);
                StorySceneKit.Set(orbit, "minPitch", -25f);
                StorySceneKit.Set(orbit, "maxPitch", 55f);
                StorySceneKit.Set(orbit, "followSmoothTime", 0.08f);
            }
            Decorate();
            EditorSceneManager.MarkSceneDirty(scene);
            EditorSceneManager.SaveScene(scene);
            AssetDatabase.SaveAssets();
        }

        public static void ApplyBatch()
        {
            try { Apply(); EditorApplication.Exit(0); }
            catch (Exception exception) { Debug.LogException(exception); EditorApplication.Exit(1); }
        }

        /// <summary>
        /// Additive, non-colliding decor for the main hall: couplets and a hanging scroll on the back wall,
        /// a rug under the contract table and water jars in the corners. Rebuilt from scratch on every run.
        /// Its materials live in the Chapter 1 folder (the story folder is regenerated by the Ch2/3 rebuild).
        /// </summary>
        private static void Decorate()
        {
            var hall = FindDeep("MainHall");
            var backWall = FindDeep("BackWall");
            if (hall == null || backWall == null) return;
            var old = hall.Find("LookDecor");
            if (old != null) UnityEngine.Object.DestroyImmediate(old.gameObject);
            var root = new GameObject("LookDecor").transform;
            root.SetParent(hall, true);

            var wall = backWall.GetComponent<Renderer>().bounds;
            float face = wall.min.z - 0.03f;
            float cx = wall.center.x;
            var red = Mat("Ch1CoupletRed", new Color(0.4f, 0.04f, 0.03f), 0.5f);
            var gold = Mat("Ch1CoupletGold", new Color(0.8f, 0.6f, 0.22f), 0.6f, 0.2f);
            var paper = Mat("Ch1ScrollPaper", new Color(0.82f, 0.75f, 0.6f), 0.1f);
            var ink = Mat("Ch1ScrollInk", new Color(0.08f, 0.06f, 0.05f), 0.1f);
            var roller = Mat("Ch1ScrollRoller", new Color(0.18f, 0.08f, 0.04f), 0.4f);
            foreach (float x in new[] { cx - 1.35f, cx + 1.35f })
            {
                Piece(root, "Couplet", new Vector3(x, 1.95f, face), new Vector3(0.32f, 1.5f, 0.03f), red);
                for (int i = 0; i < 6; i++) Piece(root, "Glyph", new Vector3(x, 2.55f - i * 0.24f, face - 0.02f), new Vector3(0.15f, 0.12f, 0.01f), gold);
            }
            Piece(root, "Scroll", new Vector3(cx, 2.35f, face), new Vector3(0.75f, 1.0f, 0.015f), paper);
            Piece(root, "ScrollTop", new Vector3(cx, 2.87f, face - 0.01f), new Vector3(0.86f, 0.05f, 0.05f), roller);
            Piece(root, "ScrollBottom", new Vector3(cx, 1.83f, face - 0.01f), new Vector3(0.86f, 0.05f, 0.05f), roller);
            // Two columns of calligraphy suggested by ink marks of varying weight.
            for (int column = 0; column < 2; column++)
                for (int i = 0; i < 4; i++)
                    Piece(root, "Brush", new Vector3(cx + 0.12f - column * 0.24f, 2.7f - i * 0.21f - column * 0.05f, face - 0.012f), new Vector3(0.12f + (i % 2) * 0.03f, 0.1f + ((i + column) % 3) * 0.025f, 0.005f), ink);

            Piece(root, "Rug", new Vector3(0, 0.022f, 3.1f), new Vector3(2.9f, 0.006f, 2.1f), Mat("Ch1Rug", new Color(0.36f, 0.06f, 0.05f), 0.05f));
            Piece(root, "RugBorder", new Vector3(0, 0.02f, 3.1f), new Vector3(3.1f, 0.005f, 2.3f), Mat("Ch1RugBorder", new Color(0.55f, 0.4f, 0.16f), 0.1f));

            var glaze = Mat("Ch1JarGlaze", new Color(0.24f, 0.15f, 0.09f), 0.7f);
            foreach (var corner in new[] { new Vector3(wall.min.x + 0.7f, 0, face - 0.6f), new Vector3(wall.max.x - 0.7f, 0, face - 0.6f) })
            {
                Piece(root, "Jar", corner + Vector3.up * 0.34f, new Vector3(0.56f, 0.68f, 0.56f), glaze, PrimitiveType.Sphere);
                Piece(root, "JarSmall", corner + new Vector3(corner.x < cx ? 0.55f : -0.55f, 0.22f, 0.1f), new Vector3(0.36f, 0.44f, 0.36f), glaze, PrimitiveType.Sphere);
            }
        }

        private static Transform FindDeep(string name)
        {
            foreach (var go in UnityEngine.SceneManagement.SceneManager.GetActiveScene().GetRootGameObjects())
                foreach (var t in go.GetComponentsInChildren<Transform>(true))
                    if (t.name == name) return t;
            return null;
        }

        private static void Piece(Transform root, string name, Vector3 position, Vector3 scale, Material material, PrimitiveType type = PrimitiveType.Cube)
        {
            var go = GameObject.CreatePrimitive(type);
            go.name = name;
            UnityEngine.Object.DestroyImmediate(go.GetComponent<Collider>());
            go.transform.SetParent(root, false);
            go.transform.position = position;
            go.transform.localScale = scale;
            go.GetComponent<Renderer>().sharedMaterial = material;
        }

        private static Material Mat(string name, Color color, float smoothness, float emission = 0f)
        {
            string path = EnvironmentMaterials + "/" + name + ".mat";
            var material = AssetDatabase.LoadAssetAtPath<Material>(path);
            if (material == null) { material = new Material(Shader.Find("Universal Render Pipeline/Lit")); AssetDatabase.CreateAsset(material, path); }
            material.SetColor("_BaseColor", color);
            material.SetFloat("_Smoothness", smoothness);
            if (emission > 0f) { material.EnableKeyword("_EMISSION"); material.SetColor("_EmissionColor", color * emission); }
            EditorUtility.SetDirty(material);
            return material;
        }

        private static void Convert(string folder, string name, string texture, Color tint, float metres, float smoothness, float grime = 0f, float normal = 1f)
        {
            if (AssetDatabase.LoadAssetAtPath<Material>(folder + "/" + name + ".mat") == null) return;
            StoryArtKit.Surface(name, texture, tint, metres, smoothness, normal, 0.35f, grime, folder);
        }
    }
